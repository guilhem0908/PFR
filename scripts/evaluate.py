def csv_text(header, rows):
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def detections_csv(scored):
    rows = []
    for image, image_rows in scored.items():
        if not image_rows:
            rows.append([image, "none", "empty_scene_no_detection"] + [""] * 9)
        for row in image_rows:
            detection, label = row["detection"], row["label"]
            rows.append([
                image, row["colour"], row["verdict"],
                *([detection["x"], detection["y"], detection["radius"]] if detection else ["", "", ""]),
                *([label["x"], label["y"], label["radius"]] if label else ["", "", ""]),
                f"{row['centre_error']:.1f}" if "centre_error" in row else "",
                row.get("radius_error", ""),
                f"{row['iou']:.2f}" if "iou" in row else "",
            ])
    return csv_text(["image", "colour", "verdict", "detected_x", "detected_y", "detected_radius",
                     "label_x", "label_y", "label_radius", "centre_error_px", "radius_error_px", "circle_iou"], rows)


def masks_csv(rows):
    return csv_text(
        ["image", "colour", "label_x", "label_y", "label_radius",
         "disc_covered", "upper_half_covered", "lower_half_covered",
         "box_x", "box_y", "box_radius", "output_x", "output_y", "output_radius",
         "box_centre_error_px", "output_centre_error_px", "box_radius_error_px", "output_radius_error_px",
         "box_iou", "output_iou"],
        [[row["image"], row["colour"],
          row["label"]["x"], row["label"]["y"], row["label"]["radius"],
          *(f"{share:.2f}" for share in row["coverage"]),
          row["box"]["x"], row["box"]["y"], row["box"]["radius"],
          row["detection"]["x"], row["detection"]["y"], row["detection"]["radius"],
          f"{row['box_errors']['centre_error']:.1f}", f"{row['output_errors']['centre_error']:.1f}",
          row["box_errors"]["radius_error"], row["output_errors"]["radius_error"],
          f"{row['box_errors']['iou']:.2f}", f"{row['output_errors']['iou']:.2f}"]
         for row in rows])


def brightness_csv(sweep):
    return csv_text(
        ["gain_percent", "balls_found", "balls_missed", "false_detections", "empty_scenes_without_detection",
         "images_fully_correct", "orange_found", "blue_found", "yellow_found"],
        [[entry["gain_percent"], entry["balls_found"], entry["balls_missed"], entry["false_detections"],
          entry["empty_scenes_without_detection"], entry["images_fully_correct"],
          *(entry["found_by_colour"][colour] for colour in COLOURS)]
         for entry in sweep])


def markdown_table(header, rows, numeric_from=1):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join(" --- " if index < numeric_from else " ---: " for index in range(len(header))) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def results_markdown(summary):
    counts = summary["detection"]
    per_colour = summary["dataset"]["balls_per_colour"]
    parts = []

    parts.append("**Detection.**\n\n" + markdown_table(
        ["On the 20 photos", "Result"],
        [["Balls found with the right colour, centre inside the labelled ball",
          f"{counts['balls_found']} / {counts['balls']}"],
         ["Balls missed", counts["balls_missed"]],
         ["False detections", counts["false_detections"]],
         ["Empty scenes with no detection", f"{counts['empty_scenes_without_detection']} / {counts['empty_scenes']}"],
         ["Images with every ball found and nothing else", f"{counts['images_fully_correct']} / {counts['images']}"]]))

    rows = []
    for key in (*COLOURS, "all"):
        stats = summary["localisation"][key]
        rows.append([key, stats["balls"], f"{stats['centre_error_median_px']:.1f}",
                     f"{stats['centre_error_max_px']:.1f}", f"{stats['radius_error_abs_median_px']:.1f}",
                     stats["radius_error_abs_max_px"], f"{stats['iou_median']:.2f}", f"{stats['iou_min']:.2f}"])
    parts.append("**Position and size.** Reported circles against the labelled circles:\n\n" + markdown_table(
        ["Colour", "Balls", "Centre error, median (px)", "Centre error, max (px)",
         "Radius error, median (px)", "Radius error, max (px)", "Circle IoU, median", "Circle IoU, min"],
        rows))

    rows = [[colour, per_colour[colour], *(f"{summary['mask_coverage'][colour][key]} %"
                                           for key in ("disc_median_percent", "upper_half_median_percent",
                                                       "lower_half_median_percent"))]
            for colour in COLOURS]
    parts.append("**What the masks catch.** Share of each labelled disc covered by the component that is kept, "
                 "median over the balls of a colour:\n\n" + markdown_table(
                     ["Colour", "Balls", "Whole disc", "Upper half", "Lower half"], rows))

    rows = []
    for colour in ("orange", "yellow"):
        for key, title in (("bounding_box", "bounding box of the mask"), ("output", "after the corrections (output)")):
            stats = summary["corrections"][colour][key]
            rows.append([colour, title, f"{stats['centre_error_median_px']:.1f}",
                         f"{stats['vertical_offset_mean_px']:+.1f}", f"{stats['radius_error_mean_px']:+.1f}",
                         f"{stats['iou_median']:.2f}"])
    parts.append("**Effect of the empirical corrections.** Orange and yellow balls, before and after "
                 "(a positive vertical offset means too low in the image):\n\n" + markdown_table(
                     ["Colour", "Estimate", "Centre error, median (px)", "Vertical offset, mean (px)",
                      "Radius error, mean (px)", "Circle IoU, median"],
                     rows, numeric_from=2))

    rows = [[f"{entry['gain_percent']} %", f"{entry['balls_found']} / {entry['balls']}",
             *(f"{entry['found_by_colour'][colour]} / {per_colour[colour]}" for colour in COLOURS),
             entry["false_detections"],
             f"{entry['images_fully_correct']} / {entry['images']}"]
            for entry in summary["brightness"]]
    parts.append("**Sensitivity to brightness.** Same photos with every RGB sample multiplied by a gain and "
                 "clipped to 255 (a simulated exposure change, not new photos):\n\n" + markdown_table(
                     ["Gain", "Balls found", "Orange", "Blue", "Yellow", "False detections", "Images fully correct"],
                     rows))

    return "\n\n".join(parts) + "\n"


def build_outputs(binary):
    labels = load_ground_truth()
    names = image_names()
    if sorted(labels) != names:
        sys.exit("ground_truth.csv and the images of IMG_300/ do not list the same names")

    masks, scored = run_photos(binary, labels)
    found = [row for rows in scored.values() for row in rows if row["verdict"] == "found"]
    mask_rows = run_masks(scored, masks)
    sweep = run_brightness(binary, labels)

    def of_colour(rows, colour):
        return [row for row in rows if row["colour"] == colour]

    def median_percent(rows, index):
        return round(100 * statistics.median(row["coverage"][index] for row in rows))

    balls_per_colour = {colour: sum(1 for balls in labels.values() for ball in balls if ball["colour"] == colour)
                        for colour in COLOURS}
    summary = {
        "criterion": "a ball is found when a detection of its colour has its centre inside the labelled circle",
        "dataset": {
            "images": len(names),
            "images_with_balls": sum(1 for balls in labels.values() if balls),
            "empty_scenes": sum(1 for balls in labels.values() if not balls),
            "balls": sum(balls_per_colour.values()),
            "balls_per_colour": balls_per_colour,
        },
        "detection": count(scored),
        "localisation": {
            **{colour: localisation(of_colour(found, colour)) for colour in COLOURS},
            "all": localisation(found),
        },
        "mask_coverage": {
            colour: {
                "disc_median_percent": median_percent(of_colour(mask_rows, colour), 0),
                "upper_half_median_percent": median_percent(of_colour(mask_rows, colour), 1),
                "lower_half_median_percent": median_percent(of_colour(mask_rows, colour), 2),
            }
            for colour in COLOURS
        },
        "corrections": {
            colour: {
                "bounding_box": localisation([row["box_errors"] for row in of_colour(mask_rows, colour)]),
                "output": localisation([row["output_errors"] for row in of_colour(mask_rows, colour)]),
            }
            for colour in ("orange", "yellow")
        },
        "brightness": sweep,
    }
    return {
        "detections.csv": detections_csv(scored),
        "masks.csv": masks_csv(mask_rows),
        "brightness.csv": brightness_csv(sweep),
        "summary.json": json.dumps(summary, indent=2) + "\n",
        "results.md": results_markdown(summary),
    }


def readme_with_results(text, block):
    start = text.find(README_START)
    end = text.find(README_END)
    if start < 0 or end < start:
        return None
    return text[:start + len(README_START)] + "\n" + block + text[end:]


def read_normalised(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--binary", help="path of the detector (default: PFR or PFR.exe at the repository root)")
    parser.add_argument("--check", action="store_true",
                        help="do not write anything; exit 1 if the committed results or README differ")
    args = parser.parse_args()

    outputs = build_outputs(find_binary(args.binary))
    readme = read_normalised(README)
    new_readme = readme_with_results(readme, outputs["results.md"]) if readme is not None else None

    if args.check:
        stale = [f"results/{name}" for name, text in outputs.items() if read_normalised(RESULTS_DIR / name) != text]
        if readme is not None and new_readme is None:
            stale.append("README.md (results markers not found)")
        elif readme is not None and new_readme != readme:
            stale.append("README.md (results block)")
        if stale:
            print("Out of date: " + ", ".join(stale))
            print("Run 'python scripts/evaluate.py' and commit the result.")
            return 1
        print(f"{len(outputs)} result files and the README tables match the detector output.")
        return 0

    RESULTS_DIR.mkdir(exist_ok=True)
    for name, text in outputs.items():
        (RESULTS_DIR / name).write_text(text, encoding="utf-8", newline="\n")
    if new_readme is not None and new_readme != readme:
        README.write_text(new_readme, encoding="utf-8", newline="\n")
    sys.stdout.write(outputs["results.md"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
