#!/usr/bin/env python3
"""Evaluate the detector on the 20 test photos against the reference labels.

The script runs the compiled C program on every text image of IMG_300/ and
compares what it reports with IMG_300/ground_truth.csv. It writes:

    results/detections.csv   one row per ball (labelled or detected)
    results/masks.csv        per ball: mask coverage, bounding box, corrected output
    results/brightness.csv   detections when the photos are darkened or brightened
    results/summary.json     every aggregate number
    results/results.md       the tables shown in the README

and refreshes the block between the 'results' markers of README.md.

    python scripts/evaluate.py            # recompute and write everything
    python scripts/evaluate.py --check    # recompute and fail if a committed file differs

Only the standard library is used; nothing here is random.
"""

import argparse
import csv
import io
import json
import math
import statistics
import sys

from common import (COLOURS, PHOTO_DIR, RESULTS_DIR, ROOT, WORK_DIR, find_binary, image_names,
                    load_ground_truth, mask_bounding_box, read_pgm, run_detector)

README = ROOT / "README.md"
README_START = "<!-- results:start (generated by scripts/evaluate.py) -->"
README_END = "<!-- results:end -->"

# Brightness sweep: every sample is multiplied by gain / 100 and clipped to 255.
BRIGHTNESS_GAINS = (50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150)


# ---------------------------------------------------------------------------
# Geometry
# ---------------------------------------------------------------------------

def circle_iou(first, second):
    """Intersection over union of two discs given as dicts with x, y, radius."""
    r1, r2 = first["radius"], second["radius"]
    distance = math.hypot(first["x"] - second["x"], first["y"] - second["y"])
    if distance >= r1 + r2:
        intersection = 0.0
    elif distance <= abs(r1 - r2):
        intersection = math.pi * min(r1, r2) ** 2
    else:
        angle1 = math.acos((distance ** 2 + r1 ** 2 - r2 ** 2) / (2 * distance * r1))
        angle2 = math.acos((distance ** 2 + r2 ** 2 - r1 ** 2) / (2 * distance * r2))
        triangle = 0.5 * math.sqrt((-distance + r1 + r2) * (distance + r1 - r2)
                                   * (distance - r1 + r2) * (distance + r1 + r2))
        intersection = r1 ** 2 * angle1 + r2 ** 2 * angle2 - triangle
    union = math.pi * (r1 ** 2 + r2 ** 2) - intersection
    return intersection / union


def compare(detection, label):
    """Localisation errors of a detection against the label of the same ball."""
    return {
        "centre_error": math.hypot(detection["x"] - label["x"], detection["y"] - label["y"]),
        "dx": detection["x"] - label["x"],
        "dy": detection["y"] - label["y"],
        "radius_error": detection["radius"] - label["radius"],
        "iou": circle_iou(detection, label),
    }


def disc_coverage(mask_rows, label):
    """Share of the labelled disc covered by a mask: (whole disc, upper half, lower half)."""
    height, width = len(mask_rows), len(mask_rows[0])
    cx, cy, radius = label["x"], label["y"], label["radius"]
    pixels = {"upper": 0, "lower": 0}
    covered = {"upper": 0, "lower": 0}
    for y in range(max(0, cy - radius), min(height, cy + radius + 1)):
        half = "upper" if y < cy else "lower"
        for x in range(max(0, cx - radius), min(width, cx + radius + 1)):
            if (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2:
                pixels[half] += 1
                covered[half] += 1 if mask_rows[y][x] else 0
    return ((covered["upper"] + covered["lower"]) / (pixels["upper"] + pixels["lower"]),
            covered["upper"] / pixels["upper"], covered["lower"] / pixels["lower"])


# ---------------------------------------------------------------------------
# Scoring
# ---------------------------------------------------------------------------

def score_image(detections, labels):
    """Match detections and labels of one image, one colour at a time.

    The detector reports at most one ball per colour and no test photo holds
    two balls of the same colour, so the match is by colour. A detection is
    'found' when its centre lies inside the labelled ball; otherwise the ball
    counts as missed and the detection as false ('misplaced').
    """
    rows = []
    for colour in COLOURS:
        label = next((ball for ball in labels if ball["colour"] == colour), None)
        detection = next((ball for ball in detections if ball["colour"] == colour), None)
        if label is None and detection is None:
            continue
        row = {"colour": colour, "label": label, "detection": detection}
        if label is None:
            row["verdict"] = "false_detection"
        elif detection is None:
            row["verdict"] = "missed"
        else:
            row.update(compare(detection, label))
            row["verdict"] = "found" if row["centre_error"] <= label["radius"] else "misplaced"
        rows.append(row)
    return rows


def count(scored):
    """Aggregate counts over {image: rows}."""
    verdicts = [row["verdict"] for rows in scored.values() for row in rows]
    labelled = {image: [row for row in rows if row["label"]] for image, rows in scored.items()}
    empty_scenes = [image for image, rows in labelled.items() if not rows]
    return {
        "balls": sum(len(rows) for rows in labelled.values()),
        "balls_found": verdicts.count("found"),
        "balls_missed": verdicts.count("missed") + verdicts.count("misplaced"),
        "false_detections": verdicts.count("false_detection") + verdicts.count("misplaced"),
        "empty_scenes": len(empty_scenes),
        "empty_scenes_without_detection": sum(1 for image in empty_scenes if not scored[image]),
        "images": len(scored),
        "images_fully_correct": sum(1 for rows in scored.values()
                                    if all(row["verdict"] == "found" for row in rows)),
    }


def localisation(rows):
    """Summary statistics over a list of compared rows."""
    centre = [row["centre_error"] for row in rows]
    radius = [row["radius_error"] for row in rows]
    iou = [row["iou"] for row in rows]
    return {
        "balls": len(rows),
        "centre_error_median_px": round(statistics.median(centre), 1),
        "centre_error_max_px": round(max(centre), 1),
        "vertical_offset_mean_px": round(statistics.mean(row["dy"] for row in rows), 1),
        "radius_error_mean_px": round(statistics.mean(radius), 1),
        "radius_error_abs_median_px": round(statistics.median(abs(value) for value in radius), 1),
        "radius_error_abs_max_px": max(abs(value) for value in radius),
        "iou_median": round(statistics.median(iou), 2),
        "iou_min": round(min(iou), 2),
    }


# ---------------------------------------------------------------------------
# Experiments
# ---------------------------------------------------------------------------

def run_photos(binary, labels):
    """Detections, masks and scores on the unmodified photos."""
    masks, scored = {}, {}
    for name in image_names():
        detections, masks[name] = run_detector(binary, PHOTO_DIR / f"{name}.txt", WORK_DIR / "photos", masks=True)
        scored[name] = score_image(detections, labels[name])
    return masks, scored


def apply_corrections(colour, x, y, radius):
    """The integer corrections of find_clusters_attributes (cluster.c)."""
    if colour == "orange":
        y = y * (10000 - 13 * radius) // 10000
    if colour == "yellow":
        y = y * (10000 + 15 * radius) // 10000
    if colour in ("orange", "yellow"):
        radius = radius * 112 // 100
    return x, y, radius


def run_masks(scored, masks):
    """Study the mask kept for each ball found.

    Reads the largest-component mask exported by the program and computes how
    much of the labelled disc it covers, and the centre and radius of its
    bounding box before the corrections (same formulas as cluster.c). As a
    consistency check, re-applying the corrections must give the program output.
    """
    rows = []
    for image, image_rows in scored.items():
        for row in image_rows:
            if row["verdict"] != "found":
                continue
            colour, detection, label = row["colour"], row["detection"], row["label"]
            _, _, mask_rows = read_pgm(masks[image][f"{colour}_largest"])
            min_x, min_y, max_x, max_y = mask_bounding_box(mask_rows)
            box = {
                "x": min_x + (max_x - min_x) // 2,
                "y": min_y + (max_y - min_y) // 2,
                "radius": max((max_x - min_x) // 2, (max_y - min_y) // 2),
            }
            expected = apply_corrections(colour, box["x"], box["y"], box["radius"])
            if expected != (detection["x"], detection["y"], detection["radius"]):
                sys.exit(f"{image} {colour}: mask bounding box {box} does not explain the output {detection}")
            rows.append({"image": image, "colour": colour, "label": label, "box": box, "detection": detection,
                         "coverage": disc_coverage(mask_rows, label),
                         "box_errors": compare(box, label), "output_errors": compare(detection, label)})
    return rows


def scale_image(source, target, gain):
    """Write a copy of a text image with every sample multiplied by gain / 100."""
    tokens = source.read_text().split()
    table = {str(value): str(min(255, (value * gain + 50) // 100)) for value in range(256)}
    target.write_text(" ".join(tokens[:3]) + "\n" + " ".join(table[token] for token in tokens[3:]) + "\n")


def run_brightness(binary, labels):
    """Detection counts when all photos are uniformly darkened or brightened."""
    work = WORK_DIR / "brightness"
    work.mkdir(parents=True, exist_ok=True)
    sweep = []
    for gain in BRIGHTNESS_GAINS:
        scored = {}
        for name in image_names():
            scaled = work / f"{name}.txt"
            scale_image(PHOTO_DIR / f"{name}.txt", scaled, gain)
            detections, _ = run_detector(binary, scaled, work)
            scored[name] = score_image(detections, labels[name])
        found_by_colour = {
            colour: sum(1 for rows in scored.values() for row in rows
                        if row["colour"] == colour and row["verdict"] == "found")
            for colour in COLOURS
        }
        sweep.append({"gain_percent": gain, **count(scored), "found_by_colour": found_by_colour})
    return sweep


